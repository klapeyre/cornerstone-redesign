import { mkdir, readFile, writeFile, rm, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import sharp from "sharp";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptDir, "..");
const srcRoot = join(repoRoot, ".gallery-src");
const outRoot = join(repoRoot, "public", "projects");
const generatedFile = join(repoRoot, "content", "gallery-images.generated.ts");

const MAX_EDGE = 2000;
const JPEG = { quality: 80, mozjpeg: true, progressive: true };

const manifest = JSON.parse(
  await readFile(join(scriptDir, "gallery-manifest.json"), "utf8"),
);

const exists = (path) =>
  access(path).then(
    () => true,
    () => false,
  );

const pad = (n) => String(n).padStart(2, "0");

const transform = (instance) =>
  instance
    .rotate()
    .resize(MAX_EDGE, MAX_EDGE, { fit: "inside", withoutEnlargement: true })
    .jpeg(JPEG);

async function processImage(srcPath, outPath) {
  try {
    return { info: await transform(sharp(srcPath)).toFile(outPath) };
  } catch {
    const info = await transform(sharp(srcPath, { failOn: "none" })).toFile(
      outPath,
    );
    return { info, lenient: true };
  }
}

const missing = [];
const failed = [];
const lenient = [];
const galleryImages = {};

for (const project of manifest.projects) {
  const outDir = join(outRoot, project.slug);
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  const images = [];

  for (let i = 0; i < project.files.length; i++) {
    const original = project.files[i];
    const srcPath = join(srcRoot, project.slug, original);
    if (!(await exists(srcPath))) {
      missing.push(`${project.slug}/${original}`);
      continue;
    }

    const name = `${pad(images.length + 1)}.jpg`;
    const outPath = join(outDir, name);

    let result;
    try {
      result = await processImage(srcPath, outPath);
    } catch (err) {
      failed.push(`${project.slug}/${original}: ${err.message || err}`);
      continue;
    }
    if (result.lenient) lenient.push(`${project.slug}/${original} -> ${name}`);

    images.push({
      src: `/projects/${project.slug}/${name}`,
      width: result.info.width,
      height: result.info.height,
    });
  }

  galleryImages[project.slug] = images;
  console.log(`${project.slug.padEnd(28)} ${images.length} images`);
}

const body = `// GENERATED by scripts/build-gallery-images.mjs — do not edit by hand.
// Source: the live cdl1983.ca gallery (see scripts/gallery-manifest.json).

export type GalleryImage = { src: string; width: number; height: number };

export const galleryImages: Record<string, GalleryImage[]> = ${JSON.stringify(
  galleryImages,
  null,
  2,
)};

export const galleryCovers: Record<string, GalleryImage | undefined> =
  Object.fromEntries(
    Object.entries(galleryImages).map(([slug, images]) => [slug, images[0]]),
  );
`;

await writeFile(generatedFile, body);

const total = Object.values(galleryImages).reduce((n, a) => n + a.length, 0);
console.log(`\n${total} images written to public/projects/`);
console.log(`wrote ${generatedFile.replace(repoRoot + "/", "")}`);

if (lenient.length) {
  console.warn(
    `\n${lenient.length} image(s) had corrupt/truncated source data and were decoded leniently — spot-check these frames:\n  ${lenient.join("\n  ")}`,
  );
}

if (missing.length) {
  console.error(
    `\n${missing.length} source file(s) missing — run scripts/fetch-gallery.mjs first:\n  ${missing.join("\n  ")}`,
  );
}

if (failed.length) {
  console.error(
    `\n${failed.length} image(s) could not be processed:\n  ${failed.join("\n  ")}`,
  );
}

if (missing.length || failed.length) process.exit(1);
